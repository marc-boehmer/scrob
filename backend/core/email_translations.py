def normalize_email_language(language: str | None) -> str:
    locale = (language or "en").replace("_", "-").lower()
    return {
        "en": "en",
        "de": "de",
        "fr": "fr",
        "pt-pt": "pt-PT",
    }.get(locale, "en")


def email_text(language: str | None, key: str) -> str:
    locale = normalize_email_language(language).lower()
    return EMAIL_TRANSLATIONS[locale][key]
